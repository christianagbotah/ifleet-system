/**
 * Zod Validation Schemas for Server-Side API Input Validation
 *
 * Provides reusable schemas for all major entities and a `validateBody` helper
 * that returns a typed discriminated union for easy early-return in API routes.
 *
 * Usage in API routes:
 *   const result = validateBody(tripCreateSchema, body)
 *   if (!result.success) return result.response
 *   // result.data is fully typed
 */

import { z } from 'zod/v4'
import { NextResponse } from 'next/server'

// ─────────────────────────────────────────────────────────────────────────────
// Common / Reusable Schemas
// ─────────────────────────────────────────────────────────────────────────────

/** CUID v1 identifier (auto-generated by Prisma) */
export const idSchema = z.string().min(1)

/** RFC 5322–ish email validation */
export const emailSchema = z
  .string()
  .email('Invalid email address')
  .max(255, 'Email must be at most 255 characters')

/**
 * Phone number — supports Ghana (+233 / 0xxx) and international formats.
 * Accepts digits, spaces, hyphens, parentheses, and a leading +.
 */
export const phoneSchema = z
  .string()
  .min(7, 'Phone number must be at least 7 digits')
  .max(20, 'Phone number must be at most 20 characters')
  .regex(/^[+\d()\- ]+$/, 'Phone number contains invalid characters')

/** Pagination parameters commonly used across list endpoints. */
export const paginationSchema = z.object({
  page: z.coerce.number().int().positive().default(1),
  limit: z.coerce.number().int().positive().max(100).default(20),
})

