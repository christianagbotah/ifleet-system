/**
 * Driver creation schema.
 * Mirrors the POST body of /api/drivers.
 *
 * Required: firstName, lastName, phone, licenseNumber, licenseExpiry, licenseClass
 */
export const driverCreateSchema = z.object({
  firstName: z.string().min(1, 'First name is required').max(50),
  lastName: z.string().min(1, 'Last name is required').max(50),
  phone: phoneSchema,
  email: emailSchema.optional().or(z.literal('')),
  licenseNumber: z.string().min(1, 'License number is required').max(50),
  licenseExpiry: z.coerce.date({ error: 'Invalid license expiry date' }),
  licenseClass: licenseClassEnum,
  licenseImage: z.string().url().optional().or(z.literal('')),

  // Ghana Card
  ghanaCardNumber: z.string().max(50).optional(),
  ghanaCardExpiry: z.coerce.date({ error: 'Invalid Ghana Card expiry date' }).optional(),
  ghanaCardFrontImage: z.string().url().optional().or(z.literal('')),
  ghanaCardBackImage: z.string().url().optional().or(z.literal('')),

  // Personal
  dateOfBirth: z.coerce.date({ error: 'Invalid date of birth' }).optional(),
  address: z.string().max(300).optional(),
  photo: z.string().url().optional().or(z.literal('')),

  // Emergency contact
  emergencyName: z.string().max(100).optional(),
  emergencyPhone: phoneSchema.optional(),

  // Employment
  employeeId: z.string().max(30).optional(),
  verificationStatus: driverVerificationStatusEnum.optional().default('pending'),

  // Linked user account creation
  createAccount: z.boolean().optional().default(false),
  accountEmail: emailSchema.optional(),
  accountPassword: z.string().min(4, 'Account password must be at least 4 characters').max(128).optional(),
}).refine(
  (data) => {
    // When createAccount is true, accountEmail and accountPassword must be present
    if (data.createAccount && (!data.accountEmail || !data.accountPassword)) {
      return false
    }
    return true
  },
  {
    message: 'accountEmail and accountPassword are required when createAccount is true',
    path: ['createAccount'],
  }
)

