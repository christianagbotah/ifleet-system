/**
 * User creation schema.
 * Mirrors the POST body of /api/users.
 *
 * Required: name, roleId
 * When hasSystemAccess (or email is provided): email + password required
 */
export const userCreateSchema = z.object({
  name: z.string().min(1, 'Name is required').max(100),
  email: emailSchema.optional().or(z.literal('')),
  phone: phoneSchema.optional().or(z.literal('')),
  password: z.string().max(128).optional(),
  roleId: idSchema,
  isActive: z.boolean().optional().default(true),
  position: z.string().max(100).optional(),
  department: z.string().max(100).optional(),
  employeeNumber: z.string().max(30).optional(),
  hasSystemAccess: z.boolean().optional(),
}).refine(
  (data) => {
    // System access users must have email + password
    const systemAccess = data.hasSystemAccess !== undefined ? data.hasSystemAccess : !!data.email
    if (systemAccess && (!data.email || !data.password)) {
      return false
    }
    return true
  },
  {
    message: 'Email and password are required for staff with system access',
    path: ['hasSystemAccess'],
  }
).refine(
  (data) => {
    // Password must be at least 4 chars when provided
    if (data.password && data.password.length < 4) {
      return false
    }
    return true
  },
  {
    message: 'Password must be at least 4 characters',
    path: ['password'],
  }
)

