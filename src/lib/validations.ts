/**
 * Trip creation schema.
 * Mirrors the POST body of /api/trips.
 *
 * Required: truckId, driverId, departureTime
 * Note: loadingLocation and destination are effectively required but can be
 * auto-populated from loadingPointId / destinationZoneId server-side, so they
 * remain optional at the schema level to let the API handle that logic.
 */
export const tripCreateSchema = z.object({
  truckId: idSchema,
  driverId: idSchema,
  departureTime: z.coerce.date({ error: 'Invalid departure time' }),

  // Identity / reference
  waybillNumber: z.string().max(50).optional(),
  itemName: z.string().max(200).optional(),
  quantity: z.union([z.string(), z.number()]).optional(),
  unit: z.string().max(20).optional().default('bags'),
  unitPrice: z.union([z.string(), z.number()]).optional(),
  totalRevenue: z.union([z.string(), z.number()]).optional(),

  // Location
  loadingLocation: z.string().max(200).optional(),
  loadingAddress: z.string().max(300).optional(),
  destination: z.string().max(200).optional(),
  destinationAddress: z.string().max(300).optional(),

  // Zone / city / point lookups (auto-populate loadingLocation / destination)
  destinationZoneId: idSchema.optional(),
  loadingPointId: idSchema.optional(),
  loadingCityId: idSchema.optional(),
  destinationCityId: idSchema.optional(),

  // Customer info
  customerName: z.string().max(150).optional(),
  customerPhone: phoneSchema.optional(),
  customerRef: z.string().max(100).optional(),

  // Trip details
  deliveryType: deliveryTypeEnum.optional(),
  startMileage: z.union([z.string(), z.number()]).optional(),
  fuelLevelBefore: z.union([z.string(), z.number()]).optional(),
  startMileageImage: z.string().url().optional().or(z.literal('')),
  markCompleted: z.boolean().optional(),

  // Free text
  notes: z.string().max(2000).optional(),

  // Nested: trip items (multi-item trips)
  tripItems: z
    .array(
      z.object({
        supplierId: z.string().optional(),
        loadingPointId: z.string().optional(),
        itemId: z.string().optional(),
        itemName: z.string().max(200).optional(),
        unit: z.string().max(20).optional().default('bags'),
        quantity: z.union([z.string(), z.number()]).optional(),
        rate: z.union([z.string(), z.number()]).optional(),
        total: z.union([z.string(), z.number()]).optional(),
        deliveryDestinationId: z.string().optional(),
      })
    )
    .optional(),

  // Nested: delivery destinations (multi-drop)
  deliveryDestinations: z
    .array(
      z.object({
        _tempId: z.string().optional(),
        stopOrder: z.union([z.string(), z.number()]).optional(),
        sortOrder: z.union([z.string(), z.number()]).optional(),
        clientId: z.string().optional(),
        customerName: z.string().max(150).optional(),
        customerPhone: phoneSchema.optional(),
        destinationZoneId: z.string().optional(),
        zoneRate: z.union([z.string(), z.number()]).optional(),
        address: z.string().max(300).optional(),
        notes: z.string().max(1000).optional(),
        status: z.string().max(50).optional(),
        actualQty: z.union([z.string(), z.number()]).optional(),
      })
    )
    .optional(),
})

