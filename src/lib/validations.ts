/**
 * Validate a request body against a Zod schema.
 *
 * Returns a discriminated union:
 *   - `{ success: true; data: T }`       — validation passed, `data` is fully typed
 *   - `{ success: false; response }`       — validation failed, `response` is a 400 NextResponse
 *
 * @example
 *   const result = validateBody(tripCreateSchema, await request.json())
 *   if (!result.success) return result.response
 *   const { truckId, driverId, departureTime } = result.data
 */
export function validateBody<T>(
  schema: z.ZodType<T>,
  body: unknown
): { success: true; data: T } | { success: false; response: NextResponse } {
  const result = schema.safeParse(body)
  if (!result.success) {
    const errors = result.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`)
    return {
      success: false,
      response: NextResponse.json(
        { error: 'Validation failed', details: errors },
        { status: 400 }
      ),
    }
  }
  return { success: true, data: result.data }
}

/**
 * Validate query parameters against a Zod schema.
 * Accepts a URLSearchParams or plain object and returns the same
 * discriminated union as `validateBody`.
 */
export function validateQuery<T>(
  schema: z.ZodType<T>,
  params: URLSearchParams | Record<string, string | string[] | undefined>
): { success: true; data: T } | { success: false; response: NextResponse } {
  const obj: Record<string, unknown> = {}
  if (params instanceof URLSearchParams) {
    params.forEach((value, key) => {
      obj[key] = value
    })
  } else {
    for (const [key, value] of Object.entries(params)) {
      if (value !== undefined) {
        obj[key] = Array.isArray(value) ? value[0] : value
      }
    }
  }
  return validateBody(schema, obj)
}
